import { chromium } from '@playwright/test';
import { mkdir } from 'node:fs/promises';
import assert from 'node:assert/strict';
await mkdir('artifacts',{recursive:true});
const browser=await chromium.launch({headless:true,channel:'msedge'});
const page=await browser.newPage({viewport:{width:1440,height:960}});
const errors=[];page.on('pageerror',e=>errors.push(String(e)));
await page.goto('http://127.0.0.1:1420');
await page.locator('.markdown-body h1').waitFor();
await page.locator('.outline-row').first().waitFor();
await page.waitForTimeout(400);
assert.equal(await page.locator('.progress-button').textContent(),'0.0%');
await page.screenshot({path:'artifacts/desktop-light.png',fullPage:true});
assert.equal(await page.locator('.markdown-body h1').textContent(),'从字节到页面：大文档的阅读架构');
assert.ok(await page.locator('.outline-row').count()>5);
await page.getByRole('button',{name:'切换主题',exact:true}).click();
assert.equal(await page.locator('html').getAttribute('data-theme'),'dark');
await page.screenshot({path:'artifacts/desktop-dark.png',fullPage:true});
await page.getByRole('button',{name:'全文搜索',exact:true}).click();
await page.getByRole('textbox',{name:'搜索关键词'}).fill('索引');
await page.locator('.search-result').first().waitFor();
await page.locator('.search-result').first().click();
await page.waitForTimeout(500);
assert.ok(await page.locator('.markdown-body mark').count()>0);
await page.screenshot({path:'artifacts/search.png',fullPage:true});
await page.getByRole('button',{name:'关闭搜索',exact:true}).click();
await page.locator('.progress-button').click();
await page.locator('.percent-input input').fill('50');
await page.getByRole('button',{name:'跳转',exact:true}).click();
assert.equal(await page.locator('.jump-dialog').count(),0);
await page.getByRole('button',{name:'阅读设置',exact:true}).click();
await page.getByRole('button',{name:'增大字号',exact:true}).click();
assert.ok((await page.locator('.font-control').textContent()).includes('17 px'));
await page.keyboard.press('Escape');
await page.getByRole('button',{name:'切换主题',exact:true}).click();
await page.setViewportSize({width:390,height:844});
await page.getByRole('button',{name:'切换侧边栏',exact:true}).click();
await page.getByRole('button',{name:'跳到开头',exact:true}).click();
await page.waitForTimeout(300);
await page.screenshot({path:'artifacts/mobile.png',fullPage:true});
const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
assert.equal(overflow,false);
assert.deepEqual(errors,[]);
console.log('UI checks passed: rendering, outline, theme, search highlighting, percentage jump, font size, mobile layout.');
await browser.close();
